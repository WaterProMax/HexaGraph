const ICON_MAP = new Map(SIDEBAR_ICONS.map((choice) => [choice.key, choice.Icon]));

export function SidebarGlyph({ name, size = 18, className = "" }: { name?: string; size?: number; className?: string }) {
  const Icon = name ? ICON_MAP.get(name) : undefined;
  if (!Icon) return null;
  return (
    <span className={`sidebar-glyph ${className}`.trim()} style={{ fontSize: size, lineHeight: 1 }} aria-hidden>
      <Icon style={{ fontSize: size }} />
    </span>
  );
}